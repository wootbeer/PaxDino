#!/usr/bin/env python3
"""
Write the N64Recomp symbol file from find_functions.py's output.

Sections (see docs/ROM_LAYOUT.md):
  .main        ROM 0x001000  vram 0x00200400  the first MB, as the code sees it (TLB entry 31)
  .main_kseg0  ROM 0x001000  vram 0x80000400  the same bytes as the data sees them; no functions,
               it only lets N64Recomp find jump tables the code reads through kseg0
  .ovl         ROM 0x164000  vram 0x00400000  code + rodata the game maps with TLB entry 0

Usage: make_syms_toml.py <functions.txt> <out.syms.toml>
"""
import sys

SECTIONS = [
    (".main", 0x001000, 0x00200400, 0x100000),
    (".main_kseg0", 0x001000, 0x80000400, 0x100000),
    (".ovl", 0x164000, 0x00400000, 0x51A50),
]


def main():
    funcs = []
    for line in open(sys.argv[1]):
        a, sz, name = line.split()[:3]
        funcs.append((int(a, 16), int(sz, 16), name))
    out = [
        "# Turok: Rage Wars (USA) symbol file for N64Recomp.",
        "# Generated by tools/make_syms_toml.py from syms/functions.txt; do not edit by hand.",
        "",
    ]
    for name, rom, vram, size in SECTIONS:
        out += ["[[section]]", f'name = "{name}"', f"rom = 0x{rom:06X}", f"vram = 0x{vram:08X}",
                f"size = 0x{size:X}", "", "functions = ["]
        for a, sz, fname in funcs:
            if vram <= a < vram + size:
                out.append(f'    {{ name = "{fname}", vram = 0x{a:08X}, size = 0x{sz:X} }},')
        out += ["]", ""]
    open(sys.argv[2], "w").write("\n".join(out))


if __name__ == "__main__":
    main()
