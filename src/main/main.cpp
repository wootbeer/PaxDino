// recompui's default options, with Add to Steam before Exit.
namespace {
    // Add to Steam closes Steam first when it's running, which takes a few
    // seconds: that runs on its own thread, and the launcher's update callback
    // shows the outcome.
    enum class SteamJob { Idle, Running, Done };
    std::atomic<SteamJob> steam_job{ SteamJob::Idle };
    std::mutex steam_job_mutex;
    trw::steam::Result steam_job_result;

    void show_steam_result(const trw::steam::Result& result) {
        if (!result.ok) {
            recompui::open_info_prompt("Add to Steam", result.error, "OK", nullptr);
            return;
        }
        recompui::open_choice_prompt(
            "Add to Steam",
            std::string(result.added ? "PaxDino was added to your Steam library" : "PaxDino's Steam shortcut was updated") +
                " as a non-Steam game" + (result.art > 0 ? ", with its artwork" : "") + ". Open Steam now?",
            "Open Steam", "Not now",
            [] { trw::steam::open_steam(); }, nullptr,
            recompui::ButtonStyle::Success, recompui::ButtonStyle::Tertiary, false);
    }

    void add_to_steam(trw::steam::Location location, bool close_first) {
        steam_job = SteamJob::Running;
        std::thread([location, close_first] {
            trw::steam::Result result;
            if (close_first && !trw::steam::close_steam_and_wait(20)) {
                result.error = "Steam didn't close. Close it yourself (Steam > Exit) and try again.";
            }
            else {
                result = trw::steam::add_shortcut(location);
            }
            {
                std::lock_guard lock{ steam_job_mutex };
                steam_job_result = result;
            }
            steam_job = SteamJob::Done;
        }).detach();
    }

    void on_add_to_steam() {
        if (steam_job != SteamJob::Idle) {
            return;
        }
        if (trw::steam::started_from_steam()) {
            recompui::open_info_prompt("Add to Steam", "PaxDino was started from Steam, so it's in your library already.", "OK", nullptr);
            return;
        }
        std::optional<trw::steam::Location> location = trw::steam::locate();
        if (!location) {
            recompui::open_info_prompt("Add to Steam", "Steam wasn't found on this computer.", "OK", nullptr);
            return;
        }
        if (trw::steam::steam_running()) {
            recompui::open_choice_prompt(
                "Add to Steam",
                "Steam has to be closed while the game is added (it rewrites its list of games when it exits). "
                "Close Steam now? It can be opened again afterwards.",
                "Close Steam", "Cancel",
                [location] {
                    recompui::open_notification("Add to Steam", "Closing Steam...");
                    add_to_steam(*location, true);
                }, nullptr,
                recompui::ButtonStyle::Success, recompui::ButtonStyle::Tertiary, false);
            return;
        }
        add_to_steam(*location, false);
    }

    void launcher_init(recompui::LauncherMenu* menu) {
        trw::launcher_art::init(menu);
        trw::crosshair::queue_previews(); // the Crosshair option's pictures
        const recomp::GameEntry& game = supported_games[0];
        recompui::GameOptionsMenu* options = menu->init_game_options_menu(
            game.game_id, game.mod_game_id, game.display_name, game.thumbnail_bytes, recompui::GameOptionsMenuLayout::Center);
        // A little lower than the frontend's 25% from the bottom, clear of the
        // logo, and no wider than it (the highlight spans the menu): the logo
        // is 30% of the window's height (src/main/launcher_art.cpp), its
        // picture 913 x 528 with the drawing in about 90% of the width, in UI
        // units of 1080 to the window's height.
        options->set_bottom(14.0f, recompui::Unit::Percent);
        options->set_width(1080.0f * 0.30f * 913.0f / 528.0f * 0.9f, recompui::Unit::Dp);
        recompui::update_game_mod_id(game.mod_game_id);
        options->add_start_game_or_load_rom_option();
        options->add_setup_controls_option();
        options->add_settings_option();
        trw::presets::add_launcher_option(options);
        options->add_mods_option();
        options->add_option("Add to Steam", on_add_to_steam);
        options->add_exit_option();
    }

    void launcher_update(recompui::LauncherMenu*) {
        trw::launcher_art::update();
        // Local Multiplayer: last launch's players, once their controllers
        // are connected.
        static bool players_restored = false;
        if (!players_restored && trw::config::get_local_multiplayer()) {
            players_restored = trw::config::restore_player_assignment();
        }
        if (steam_job == SteamJob::Done) {
            trw::steam::Result result;
            {
                std::lock_guard lock{ steam_job_mutex };
                result = steam_job_result;
            }
            steam_job = SteamJob::Idle;
            show_steam_result(result);
        }
    }
}

int main(int argc, char** argv) {
#ifdef _WIN32
    // Release builds have no console, so the runtime's error messages (e.g.
    // "Failed to find function", unhandled exception text) would be lost.
    // Keep them in trw_log.txt next to crash_log.txt.
    if (GetConsoleWindow() == nullptr) {
        if (freopen("trw_log.txt", "w", stderr) != nullptr) {
            setvbuf(stderr, nullptr, _IONBF, 0);
        }
        freopen("trw_log.txt", "a", stdout);
    }
#endif
    std::set_terminate(report_unhandled_exception_and_abort);

    recomp::Version project_version{};
    if (!recomp::Version::from_string(version_string, project_version)) {
        fprintf(stderr, "Invalid version string: %s\n", version_string.c_str());
        return EXIT_FAILURE;
    }

    register_trw_overlays();
    trw::apply_theme();

    NFD_Init();

    recompui::programconfig::set_program_name(program_name);
    recompui::programconfig::set_program_id(program_id);

    SDL_InitSubSystem(SDL_INIT_AUDIO);
    if (!open_audio_device(game_frequency)) {
        fprintf(stderr, "Continuing without sound.\n");
    }

    // Exo 2 (SIL OFL 1.1, assets/EXO2_LICENSE.txt), a variable font covering
    // every weight the UI uses. The family name must match the one stored
    // inside the font file: recompui's generated base stylesheet sets
    // `font-family` to it, and RmlUi draws no text for a family it never
    // loaded (STATUS.md round 86).
    recompui::register_primary_font("Exo2.ttf", "Exo 2");

    recomp::register_config_path(recompui::file::get_app_folder_path());
    trw::music::create_folder(); // Custom Music's folder, beside the executable

    for (const auto& game : supported_games) {
        recomp::register_game(game);
    }

    recompinput::players::set_single_player_mode(true);

    // recompui::config::init_modal() (called from UIState::create_menus(),
    // itself called from inside RT64::Application::setup() on the gfx
    // thread) hard-requires recompui::config::finalize() to have already
    // run -- without it, "loaded_configs" stays false and/or the config
    // system is left in a state RT64/recompui doesn't expect, which was
    // crashing startup entirely (see STATUS.md). So the config tabs are
    // created and finalized here, before recomp::start().
    trw::controls::set_keyboard_defaults();
    trw::controls::set_controller_defaults();
    recompui::config::GeneralTabOptions general_tab_options{};
    general_tab_options.has_mouse_sensitivity = true;
    trw::config::add_general_options(recompui::config::create_general_tab(general_tab_options));
    recompui::config::set_graphics_options_after_aspect_ratio(trw::config::add_graphics_options_after_aspect_ratio);
    recompui::config::set_graphics_options_after_msaa(trw::config::add_graphics_options_after_msaa);
    trw::config::add_graphics_options(recompui::config::create_graphics_tab());
    recompui::config::create_controls_tab();
    recompui::config::create_sound_tab();
    trw::config::add_extra_tabs();
    // Last on the strip: there are no mods for this game yet.
    recompui::config::create_mods_tab();
    trw::presets::note_first_launch();
    recompui::config::finalize();
    trw::presets::apply_first_launch();
    trw::controls::update_controller_profiles(recomp::get_config_path());

    // Read from the just-loaded config; takes effect on the next launch if
    // changed in the menu.
    if (trw::config::get_local_multiplayer()) {
        recompinput::players::set_single_player_mode(false);
        recompinput::playerassignment::set_commit_callback(trw::config::save_player_assignment);
    }

    recomp::rsp::callbacks_t rsp_callbacks{
        .get_rsp_microcode = get_rsp_microcode,
    };

    ultramodern::renderer::callbacks_t renderer_callbacks{
        .create_render_context = [](uint8_t* rdram, ultramodern::renderer::WindowHandle window_handle, bool developer_mode) -> std::unique_ptr<ultramodern::renderer::RendererContext> {
            auto presentation_mode = ultramodern::renderer::PresentationMode::PresentEarly;
            return std::make_unique<TrwRendererContext>(recompui::renderer::create_render_context(rdram, window_handle, presentation_mode, developer_mode));
        },
    };

    ultramodern::gfx_callbacks_t gfx_callbacks{
        .create_gfx = create_gfx,
        .create_window = create_window,
        .update_gfx = update_gfx,
    };

    ultramodern::audio_callbacks_t audio_callbacks{
        .queue_samples = queue_samples,
        .get_frames_remaining = get_frames_remaining,
        .set_frequency = set_frequency,
    };

    ultramodern::input::callbacks_t input_callbacks{
        .poll_input = trw::controls::poll_input,
        .get_input = trw::controls::get_input,
        .set_rumble = recompinput::set_rumble,
        .get_connected_device_info = get_connected_device_info,
    };

    ultramodern::events::callbacks_t events_callbacks{
        .vi_callback = recompinput::update_rumble,
        .gfx_init_callback = nullptr,
    };

    ultramodern::error_handling::callbacks_t error_handling_callbacks{
        .message_box = recompui::message_box,
    };

    ultramodern::threads::callbacks_t threads_callbacks{
        .get_game_thread_name = get_game_thread_name,
    };

    recompui::register_launcher_init_callback(launcher_init);
    recompui::register_launcher_update_callback(launcher_update);

    recomp::start({
        .argc = argc,
        .argv = argv,
        .project_version = project_version,
        .window_handle = {}, // created by gfx_callbacks.create_window
        .rsp_callbacks = rsp_callbacks,
        .renderer_callbacks = renderer_callbacks,
        .audio_callbacks = audio_callbacks,
        .input_callbacks = input_callbacks,
        .gfx_callbacks = gfx_callbacks,
        .events_callbacks = events_callbacks,
        .error_handling_callbacks = error_handling_callbacks,
        .threads_callbacks = threads_callbacks,
        .message_queue_control = {}, // the runtime's defaults
    });

    NFD_Quit();

    // The game's threads are never joined by the runtime and may still be
    // blocked on (or spinning over) runtime state when recomp::start
    // returns, so running static destructors/atexit handlers underneath
    // them can crash on quit -- exit directly instead (same approach as
    // other N64Recomp projects' main()).
    fflush(stdout);
    fflush(stderr);
    std::_Exit(EXIT_SUCCESS);
}
