// --- Audio ----------------------------------------------------------------
// Push-based playback: queue whatever the game hands us, report how much is
// still queued. SDL converts from the game's sample rate to the device's.

static SDL_AudioDeviceID audio_device = 0;
static std::mutex audio_mutex;
static constexpr uint32_t audio_channels = 2;
static uint32_t game_frequency = 44100;

// Extra audio the game is told it still needs to generate, beyond what's
// actually queued. The game sizes each audio task from osAiGetLength, so
// without this margin a late audio thread wakeup (they're host threads here,
// not hardware interrupts) lets the queue run dry for a moment: crackle.
static constexpr uint32_t audio_headroom_vis = 2;

// Latency cap. Nothing drains a surplus on its own: when the game delivers a
// burst faster than real time (e.g. skipping a cutscene), the extra stays
// queued and every sound after it plays late by that much. Above the soft
// cap incoming chunks are dropped until it's back under (a small surplus
// drains without a gap); above the hard cap the queue is cleared at once.
static constexpr uint32_t audio_soft_cap_ms = 200;
static constexpr uint32_t audio_hard_cap_ms = 500;

static bool open_audio_device(uint32_t frequency) {
    std::lock_guard<std::mutex> lock(audio_mutex);

    if (audio_device != 0) {
        SDL_CloseAudioDevice(audio_device);
        audio_device = 0;
    }

    SDL_AudioSpec desired{};
    desired.freq = static_cast<int>(frequency);
    desired.format = AUDIO_F32SYS;
    desired.channels = static_cast<Uint8>(audio_channels);
    desired.samples = 512;

    // No allowed changes: SDL resamples to whatever the device runs at, so
    // queued audio is always in the game's own rate.
    audio_device = SDL_OpenAudioDevice(nullptr, 0, &desired, nullptr, 0);
    game_frequency = frequency;
    if (audio_device == 0) {
        fprintf(stderr, "Failed to open audio device: %s (continuing without sound)\n", SDL_GetError());
        return false;
    }

    SDL_PauseAudioDevice(audio_device, 0);
    return true;
}

// Audio queued while there's no audio device, and polls answered "not full"
// since audio was last queued, for trw_osAiGetStatus below.
static std::atomic<int> ai_polls_without_audio{ 0 };
static std::atomic<uint64_t> virtual_ai_queued_frames{ 0 };
static std::chrono::steady_clock::time_point virtual_ai_start = std::chrono::steady_clock::now();

static void queue_samples(int16_t* audio_data, size_t sample_count) {
    ai_polls_without_audio = 0;
    if (audio_device == 0) {
        virtual_ai_queued_frames += sample_count / audio_channels;
        return;
    }

    // Each stereo frame is one 32-bit word in RDRAM, which is stored
    // word-swapped, so the two 16-bit halves read back right-then-left.
    static std::vector<float> buffer;
    buffer.resize(sample_count);
    float scale = static_cast<float>(recompui::config::sound::get_main_volume() / 100.0) / 32768.0f;
    for (size_t i = 0; i + 1 < sample_count; i += 2) {
        buffer[i + 0] = audio_data[i + 1] * scale;
        buffer[i + 1] = audio_data[i + 0] * scale;
    }

    // Custom Music (src/main/custom_music.cpp) plays on top, mixed into
    // what's actually queued (a dropped buffer mustn't move it on).
    auto queue = [&] {
        trw::music::mix(buffer.data(), sample_count / 2, game_frequency, scale * 32768.0f);
        SDL_QueueAudio(audio_device, buffer.data(), static_cast<Uint32>(sample_count * sizeof(float)));
    };

    std::lock_guard<std::mutex> lock(audio_mutex);
    const size_t bytes_per_ms = game_frequency * audio_channels * sizeof(float) / 1000;
    const size_t queued_bytes = SDL_GetQueuedAudioSize(audio_device);
    if (queued_bytes > audio_hard_cap_ms * bytes_per_ms) {
        printf("[TRW AUDIO] %zu ms queued, resyncing\n", queued_bytes / bytes_per_ms);
        fflush(stdout);
        SDL_ClearQueuedAudio(audio_device);
    }
    else if (queued_bytes > audio_soft_cap_ms * bytes_per_ms) {
        return;
    }
    queue();
}

// The game's audio thread (0x00256C30) makes audio frames while
// osAiGetStatus() doesn't report AI_STATUS_FIFO_FULL, the way the N64's
// two-buffer AI FIFO paces it. The runtime's osAiGetStatus always returns 0,
// so the game gets its own: full once about two frames of audio are queued.
// Without an audio device, queued audio drains in real time.

static size_t queued_audio_frames() {
    if (audio_device != 0) {
        std::lock_guard<std::mutex> lock(audio_mutex);
        return SDL_GetQueuedAudioSize(audio_device) / (audio_channels * sizeof(float));
    }
    double elapsed = std::chrono::duration<double>(std::chrono::steady_clock::now() - virtual_ai_start).count();
    uint64_t played = (uint64_t)(elapsed * game_frequency);
    uint64_t queued = virtual_ai_queued_frames.load();
    if (played > queued) {
        // Nothing queued: restart the clock so silence doesn't build credit.
        virtual_ai_start = std::chrono::steady_clock::now();
        virtual_ai_queued_frames = 0;
        return 0;
    }
    return (size_t)(queued - played);
}

// Polls answered "not full" since audio was last queued. The audio thread
// makes frames until the FIFO is full, but a frame can come out empty (no
// sound playing, e.g. while the game is still setting up its players); then
// nothing is queued and it would spin forever at high priority, starving the
// threads that would start the sound. After two empty polls the FIFO counts
// as full, and the audio thread waits for the next retrace instead.
extern "C" void trw_osAiGetStatus(uint8_t*, recomp_context* ctx) {
    constexpr uint32_t AI_STATUS_FIFO_FULL = 0x80000000u;
    size_t two_frames = game_frequency / 30;
    bool full = queued_audio_frames() >= two_frames || ai_polls_without_audio >= 2;
    if (!full) {
        ai_polls_without_audio++;
    }
    ctx->r2 = full ? AI_STATUS_FIFO_FULL : 0;
}

static size_t get_frames_remaining() {
    if (audio_device == 0) {
        return 0;
    }
    std::lock_guard<std::mutex> lock(audio_mutex);
    size_t queued_frames = SDL_GetQueuedAudioSize(audio_device) / (audio_channels * sizeof(float));
    size_t headroom_frames = game_frequency / 60 * audio_headroom_vis;
    return queued_frames > headroom_frames ? queued_frames - headroom_frames : 0;
}

static void set_frequency(uint32_t frequency) {
    if (frequency != game_frequency) {
        open_audio_device(frequency);
    }
}

// --- Input ------------------------------------------------------------

// Port 1 is always plugged in. In local multiplayer, so is one port per
// assigned player; in single-player mode every controller drives player 1,
// so the other ports must stay empty or they'd mirror player 1's input.
//
// The runtime's Pak enum has no Controller Pak, so any pak is reported as a
// Rumble Pak here; that only sets "something is plugged in" in the status
// the game queries.
static ultramodern::input::connected_device_info_t get_connected_device_info(int controller_num) {
    size_t ports = 1;
    if (!recompinput::players::is_single_player_mode()) {
        ports = std::max<size_t>(1, recompinput::players::get_number_of_assigned_players());
    }
    if (controller_num < 0 || (size_t)controller_num >= ports) {
        return ultramodern::input::connected_device_info_t{
            .connected_device = ultramodern::input::Device::None,
            .connected_pak = ultramodern::input::Pak::None,
        };
    }
    bool has_pak = trw::config::get_accessory(controller_num) != trw::config::Accessory::None;
    return ultramodern::input::connected_device_info_t{
        .connected_device = ultramodern::input::Device::Controller,
        .connected_pak = has_pak ? ultramodern::input::Pak::RumblePak : ultramodern::input::Pak::None,
    };
}

